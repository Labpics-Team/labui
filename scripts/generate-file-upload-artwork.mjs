import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const source = new URL('assets/file-upload/', root);
const native = new URL('native/compose/src/commonMain/composeResources/drawable/', root);
const artwork = {};
const check = process.argv.includes('--check');
if (!check) await mkdir(native, { recursive: true });
async function outputFile(path, content) {
  if (check) {
    const expected = Buffer.isBuffer(content) ? content : Buffer.from(content);
    if (!(await readFile(path)).equals(expected))
      throw new Error(`File Upload artwork is stale: ${path.pathname}`);
  } else await writeFile(path, content);
}
for (const name of ['default', 'hover', 'selected', 'drag', 'drag-background', 'file']) {
  const extension = name === 'file' ? 'svg' : 'png';
  const bytes = await readFile(new URL(`${name}.${extension}`, source));
  artwork[name] =
    `data:image/${extension === 'svg' ? 'svg+xml' : 'png'};base64,${bytes.toString('base64')}`;
  if (extension === 'png')
    await outputFile(new URL(`lab_file_upload_${name.replaceAll('-', '_')}.png`, native), bytes);
  if (extension === 'svg') {
    const svg = bytes.toString('utf8');
    const paths = [...svg.matchAll(/<path\s+([^>]+)\/>/g)].map(([, attributes]) => {
      const attr = (key) => attributes.match(new RegExp(`(?:^|\\s)${key}="([^"]*)"`))?.[1];
      // The exact contour is painted with the runtime semantic label role (including its alpha).
      return `  <path android:pathData="${attr('d')}" android:fillColor="#FFFFFFFF" android:fillType="${attr('fill-rule') === 'evenodd' ? 'evenOdd' : 'nonZero'}" />`;
    });
    if (!paths.length) throw new Error('File Upload glyph has no authored paths');
    await outputFile(
      new URL('lab_file_upload_file.xml', native),
      `<!-- Generated from assets/file-upload/file.svg. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.join('\n')}\n</vector>\n`,
    );
  }
}
const content = `// Generated by scripts/generate-file-upload-artwork.mjs from exact authored artwork.\nexport const fileUploadArtwork = ${JSON.stringify(artwork, null, 2)} as const;\n`;
const output = new URL('packages/core/src/components/file-upload/artwork.generated.ts', root);
await outputFile(output, content);
