import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { chromium, firefox, webkit } from '@playwright/test';

// Run from the external packed consumer. Every written PNG is recorded for pixel verification.
// node capture.mjs <HTTP URL> <integration evidence directory> <retained evidence directory>
const [url, output, retained] = process.argv.slice(2);
assert.ok(url && output && retained, 'Supply the URL and both evidence directories');
for (const directory of [output, retained]) mkdirSync(directory, { recursive: true });
const result = [];
async function capture(page, browser, metadata, paths, count) {
  const { theme, contrast } = metadata;
  await page.evaluate(
    ({ theme, contrast }) => {
      Object.assign(document.documentElement.dataset, { theme, contrast });
    },
    { theme, contrast },
  );
  const materials = await page.evaluate(async () => {
    await document.fonts.ready;
    const elements = [
      ...document.querySelectorAll('.lab-avatar-texture'),
      ...[...document.querySelectorAll('lab-avatar')].flatMap((host) => [
        ...host.shadowRoot.querySelectorAll('.lab-avatar-texture'),
      ]),
    ];
    return Promise.all(
      elements.map(async (el) => {
        const background = getComputedStyle(el).backgroundImage;
        const url = background.match(/^url\("(.+)"\)$/)?.[1];
        if (!url) throw new Error(`Missing background URL: ${background}`);
        const image = new Image();
        image.src = url;
        // Loading the page or fonts does not wait for new CSS theme images.
        await image.decode();
        const canvas = document.createElement('canvas');
        canvas.width = canvas.height = 48;
        const context = canvas.getContext('2d');
        context.drawImage(image, 0, 0, 48, 48);
        const pixels = context.getImageData(12, 12, 24, 24).data;
        const distinct = new Set();
        for (let i = 0; i < pixels.length; i += 4)
          distinct.add(`${pixels[i]},${pixels[i + 1]},${pixels[i + 2]}`);
        const box = el.getBoundingClientRect();
        return {
          url,
          width: image.naturalWidth,
          height: image.naturalHeight,
          distinct: distinct.size,
          box: { x: box.x, y: box.y, width: box.width, height: box.height },
        };
      }),
    );
  });
  assert.equal(materials.length, count);
  for (const material of materials) {
    assert.ok(new URL(material.url).pathname.startsWith('/dist/assets/'), material.url);
    assert.ok(material.url.includes(`-${theme}-${contrast}-`), material.url);
    assert.equal(material.width, 256);
    assert.equal(material.height, 256);
    assert.ok(material.distinct > 250, `${material.url}: flat decoded material`);
  }
  await page.evaluate(
    () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
  );
  const pixels = await page.screenshot();
  const files = [];
  for (const path of paths) {
    writeFileSync(path, pixels);
    files.push(relative(output, path).replaceAll('\\', '/'));
  }
  result.push({ ...metadata, version: browser.version(), files, materials });
}
for (const [name, engine] of Object.entries({ chromium, firefox, webkit })) {
  const browser = await engine.launch({ headless: true });
  try {
    for (const density of name === 'chromium' ? [1, 2] : [1]) {
      const page = await browser.newPage({
        viewport: { width: 800, height: 400 },
        deviceScaleFactor: density,
      });
      const errors = [];
      page.on('pageerror', (error) => errors.push(error.message));
      const requests = new Set();
      page.on('request', (request) => {
        if (request.url().endsWith('.webp')) requests.add(request.url());
      });
      await page.goto(`${url}?matrix`);
      await page.locator('.react .lab-avatar-texture').last().waitFor();
      for (const theme of ['light', 'dark'])
        for (const contrast of ['normal', 'more']) {
          const suffix = `${theme}-${contrast}-${density * 100}.png`;
          const paths = [join(output, `installed-${name}-${suffix}`)];
          if (name === 'chromium') paths.push(join(retained, `installed-web-${suffix}`));
          await capture(page, browser, { browser: name, theme, contrast, density }, paths, 40);
        }
      assert.equal(requests.size, 40);
      assert.deepEqual(errors, []);
      await page.close();
    }
    // These previously retained screenshots are generated by the same capture path and manifest.
    const smoke = await browser.newPage({ viewport: { width: 1280, height: 720 } });
    await smoke.goto(url);
    await smoke.locator('.react .lab-avatar-texture').waitFor();
    await capture(
      smoke,
      browser,
      { browser: name, theme: 'light', contrast: 'normal', density: 1 },
      [join(retained, `installed-${name}.png`)],
      2,
    );
    await smoke.close();
    if (name === 'chromium') {
      const zoom = await browser.newPage({
        viewport: { width: 1440, height: 700 },
        deviceScaleFactor: 2,
      });
      await zoom.goto(`${url}?matrix`);
      await zoom.locator('.react .lab-avatar-texture').last().waitFor();
      await zoom.evaluate(() => {
        document.documentElement.style.fontSize = '32px';
      });
      await capture(
        zoom,
        browser,
        { browser: name, theme: 'dark', contrast: 'more', density: 2, fontScale: 2 },
        [join(retained, 'installed-web-dark-more-zoom200-dpr2.png')],
        40,
      );
      await zoom.close();
    }
  } finally {
    await browser.close();
  }
}
writeFileSync(join(output, 'installed-materials.json'), `${JSON.stringify(result, null, 2)}\n`);
console.info(
  `Captured ${result.reduce((count, capture) => count + capture.files.length, 0)} PNG files; verify their actual pixels with verify-capture.py.`,
);
